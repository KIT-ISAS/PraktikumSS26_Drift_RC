#!/bin/bash
AMENT_FLAKE8_CONFIG=/opt/ros/jazzy/lib/python3.12/site-packages/ament_flake8/configuration/ament_flake8.ini
AMENT_PEP257_MAIN=/opt/ros/jazzy/lib/python3.12/site-packages/ament_pep257/main.py

# This script is idempotent: post_start.sh re-runs it on every container start,
# so each step must avoid duplicating config. A duplicated key makes flake8's
# configparser raise DuplicateOptionError and breaks `colcon test`.

# Ignore D401 "First line of Docstring should be in imperative mood" and I101.
# Collapse any prior repeats to a single occurrence, then add once if missing.
sed -i -E 's/(,D401,I101)+/,D401,I101/' $AMENT_FLAKE8_CONFIG
grep -qE ',D401,I101' $AMENT_FLAKE8_CONFIG || \
    sed -i -E 's/^(extend-ignore = .*)$/\1,D401,I101/' $AMENT_FLAKE8_CONFIG
grep -q "'D401'," $AMENT_PEP257_MAIN || \
    sed -i "/_ament_ignore = \[/,/\]/ s/\]/    'D401',\n]/" $AMENT_PEP257_MAIN

# Configure flake8 to allow double quotes to avoid conflicts with Ruff's formatter.
# Delete any previous additions first so re-runs don't duplicate the keys.
sed -i '/^inline-quotes = /d; /^application-import-names = /d' $AMENT_FLAKE8_CONFIG
echo 'inline-quotes = "' >> $AMENT_FLAKE8_CONFIG

# Add all packages in the workspace to application-import-names so flake8 doesn't
# complain about imports from other workspace packages. See README.md.
# This list is regenerated by update_package_list.sh.
PACKAGES=(car_localization_pkg,example_pkg,holodeck_pkg,joystick_pkg,shared_interfaces,shared_pkg,simulation_pkg,steamvr_pkg,track_pkg,vehicle_communication_pkg,vehicle_simulation)
echo "application-import-names = $PACKAGES" >> $AMENT_FLAKE8_CONFIG
